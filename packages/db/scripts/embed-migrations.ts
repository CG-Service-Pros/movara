/**
 * Embeds drizzle/*.sql into src/migrations.generated.ts so `migrate(db)` works when the
 * package is bundled (Next.js) and no filesystem path to ./drizzle is available.
 * Run automatically by `pnpm db:generate`.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const journal = JSON.parse(readFileSync(join(root, 'drizzle', 'meta', '_journal.json'), 'utf8')) as {
  entries: { idx: number; when: number; tag: string; breakpoints: boolean }[]
}
const migrations = journal.entries.map((e) => {
  const raw = readFileSync(join(root, 'drizzle', `${e.tag}.sql`), 'utf8')
  return {
    tag: e.tag,
    folderMillis: e.when,
    hash: createHash('sha256').update(raw).digest('hex'),
    sql: raw.split('--> statement-breakpoint'),
  }
})
const out = `// GENERATED by scripts/embed-migrations.ts from ./drizzle. Do not edit.\nexport const MIGRATIONS: { tag: string; folderMillis: number; hash: string; sql: string[] }[] = ${JSON.stringify(migrations, null, 2)}\n`
writeFileSync(join(root, 'src', 'migrations.generated.ts'), out)
console.log(`embedded ${migrations.length} migration(s)`)
