import { expect, test } from '@playwright/test'

test('recovery is reachable while signed out and handles request and reset states', async ({ page }) => {
  await page.goto('/sign-in')
  await page.getByRole('link', { name: 'Forgot password?' }).click()
  await expect(page).toHaveURL(/\/forgot-password$/)
  await page.route('**/api/auth/request-password-reset', async (route) => {
    expect(route.request().postDataJSON()).toEqual({ email: 'recovery@example.com', redirectTo: '/reset-password' })
    await route.fulfill({ json: { status: true } })
  })
  await page.getByLabel('Email').fill('recovery@example.com')
  await page.getByRole('button', { name: 'Send reset link' }).click()
  await expect(page.getByRole('status')).toContainText('If an account exists')

  await page.goto('/reset-password')
  await expect(page.locator('p[role="alert"]')).toContainText('invalid or has expired')
  await page.goto('/reset-password?error=INVALID_TOKEN')
  await expect(page.getByRole('link', { name: 'Request a new reset link' })).toBeVisible()
  await page.goto('/reset-password?token=test-token')
  await page.getByLabel('New password', { exact: true }).fill('replacement-password')
  await page.getByLabel('Confirm new password').fill('different-password')
  await page.getByRole('button', { name: 'Reset password', exact: true }).click()
  await expect(page.locator('p[role="alert"]')).toHaveText('Passwords do not match.')
  await page.route('**/api/auth/reset-password', async (route) => {
    expect(route.request().postDataJSON()).toEqual({ token: 'test-token', newPassword: 'replacement-password' })
    await route.fulfill({ json: { status: true } })
  })
  await page.getByLabel('Confirm new password').fill('replacement-password')
  await page.getByRole('button', { name: 'Reset password', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Your password has been reset.')
  await expect(page).toHaveURL(/\/reset-password$/)
  await page.getByRole('link', { name: 'Sign in with your new password' }).click()
  await expect(page).toHaveURL(/\/sign-in$/)
})

test('recovery shows service and expired-token errors with a way to retry', async ({ page }) => {
  await page.goto('/forgot-password')
  await page.route('**/api/auth/request-password-reset', (route) => route.fulfill({ status: 503, json: { message: 'Unavailable' } }))
  await page.getByLabel('Email').fill('recovery@example.com')
  await page.getByRole('button', { name: 'Send reset link' }).click()
  await expect(page.locator('p[role="alert"]')).toContainText('contact your administrator')
  await expect(page.getByRole('button', { name: 'Send reset link' })).toBeEnabled()
  await page.goto('/reset-password?token=expired-token')
  await page.route('**/api/auth/reset-password', (route) => route.fulfill({ status: 400, json: { code: 'INVALID_TOKEN', message: 'Invalid token' } }))
  await page.getByLabel('New password', { exact: true }).fill('replacement-password')
  await page.getByLabel('Confirm new password').fill('replacement-password')
  await page.getByRole('button', { name: 'Reset password', exact: true }).click()
  await expect(page.locator('p[role="alert"]')).toContainText('invalid or has expired')
  await page.getByRole('link', { name: 'Request a new reset link' }).click()
  await expect(page).toHaveURL(/\/forgot-password$/)
})
